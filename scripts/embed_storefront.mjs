// Copies the built Storefront HTML into a TypeScript module, so the Worker can serve it without file access (ADR-009).
import { readFileSync, writeFileSync } from "node:fs";

const html = readFileSync("storefront/dist/index.html", "utf8");
const out = `// GENERATED by scripts/embed_storefront.mjs. Never edit by hand (AGENTS.md rule 8).\nexport const STOREFRONT_HTML: string = ${JSON.stringify(html)};\n`;
writeFileSync("src/server/mcp/storefront.generated.ts", out);
console.log(`storefront: ${html.length} bytes`);
